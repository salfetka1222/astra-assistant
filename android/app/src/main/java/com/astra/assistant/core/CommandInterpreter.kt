package com.astra.assistant.core

/** Offline, deterministic command hints. No arbitrary shell or Accessibility execution. */
internal object CommandInterpreter {
    fun interpret(input: String): String? {
        val text = input.trim().lowercase().replace(Regex("\\s+"), " ")
        return when (text) {
            "что ты умеешь", "команды", "список команд" ->
                "Я умею сохранять чат, показывать диагностику телефона и выполнять разрешённые действия через раздел «Инструменты → Мост Termux». Примеры: «открой настройки», «покажи файлы», «проверь батарею», «что нового». Действия запускаются только после нажатия соответствующей кнопки."
            "открой настройки", "настройки android" ->
                "Открой «Инструменты → Мост Termux → Открыть: Настройки Android». Я не открываю приложения автоматически из текста чата."
            "покажи файлы", "список файлов", "файлы termux" ->
                "Открой «Инструменты → Мост Termux → Показать workspace». Требуется запущенный мост и токен."
            "проверь батарею", "заряд батареи", "диагностика" ->
                "Открой «Инструменты → Мост Termux → Батарея, ОЗУ и память»."
            "что нового", "изменения", "история обновлений" ->
                "Открой «Настройки → Что нового в Astra», чтобы увидеть изменения последнего выпуска."
            else -> null
        }
    }
}
